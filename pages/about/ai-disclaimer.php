                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>No Copyrighted Triggers:</strong> We never use real artist names or copyrighted song titles in our prompts to ensure 100% original sonic output.</li>
                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>Clean Styles:</strong> Every song is built on a self-contained, keyword-heavy Styles prompt that dictates the exact genre, instrumentation, and era.</li>
                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>Diacritical & Cultural Precision:</strong> We mandate the exact typographic representation of proper indigenous names and locations. For example, we require the precise spelling <strong>Uluṟu</strong>—strictly rejecting both the colonial name "Ayers Rock" and the unaccented "Uluru." We similarly enforce proper accents for locations like Québec and Montréal.</li>
                            </ul>
                        </div>
                        <div class="col-md-6">
                            <ul class="list-group list-group-flush bg-transparent">
                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>Phonetic Control:</strong> AI struggles with local names. We manually spell out acronyms and fictional locations phonetically to force perfect pronunciation.</li>
                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>Iterative Budgeting:</strong> Creating a final track often requires rendering dozens of variations, adjusting the "Weirdness" parameters, and piecing together extensions to get the perfect narrative fit.</li>
                                <li class="list-group-item bg-transparent border-0 text-body-emphasis"><i class="ph ph-angle-right text-primary me-2" aria-hidden="true"></i><strong>Visual Blueprinting:</strong> We do not rely on single-shot text prompts for visual assets. We utilize Image-to-Image blueprints and low-denoising workflows to force the AI to adhere to exact typographic layouts, overriding its tendency to hallucinate lettering.</li>
                            </ul>
